const peso1 = 15;
const peso2 = 5;

console.log(peso1 + peso2); // 20 - suma de pesos
console.log(peso1 - peso2); // 10 - diferencia
console.log(peso1 * 2);     // 30 - dosis doble
console.log(peso1 / 2);     // 7.5 - mitad de dosis
console.log(peso1 % 4);     // 3 - resto
console.log(2 ** 3);        // 8 - potencia
